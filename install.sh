#!/usr/bin/env bash
# boardkit without the Claude Code plugin: for Codex, other agents, or a
# machine without the plugin. It installs what the plugin carries, the same
# way: the `board` launcher and the skills, at one version, for the user and
# never inside a repository.
#
#   bash install.sh            the latest release
#   bash install.sh 0.3.24     that release
#   board self update          the same, later
#   bash install.sh --uninstall  remove the command and the skills it wrote
#
# It needs bash and git. The first `board` then fetches boardkit itself (and
# uv and gh if the machine has neither), exactly as the plugin's does.
#
# BOARDKIT_SOURCE=<checkout> installs from a checkout instead of a tag, for
# testing this script. BOARDKIT_HOME and BOARDKIT_BIN move where it installs.
set -euo pipefail

REPO="https://github.com/deucalion-x/boardkit"
home="${BOARDKIT_HOME:-$HOME/.local/share/boardkit}"
bin="${BOARDKIT_BIN:-$HOME/.local/bin}"
say() { echo "boardkit: $*" >&2; }

# Each agent's user skill directory. Claude's is skipped when the plugin is
# installed, which carries the same skills: two copies would both load.
targets=("${CODEX_HOME:-$HOME/.codex}/skills")
if [ -d "$HOME/.claude" ] && [ ! -d "$HOME/.claude/plugins/cache/boardkit" ]; then
  targets+=("$HOME/.claude/skills")
fi

if [ "${1:-}" = "--uninstall" ]; then
  if grep -qs '^# boardkit install.sh' "$bin/board"; then rm "$bin/board"; fi
  for target in "$HOME/.claude/skills" "${CODEX_HOME:-$HOME/.codex}/skills"; do
    for name in board board-admin; do
      # Only ours: the banner every generated skill carries.
      if grep -qs 'Generated by `board install-skill`' "$target/$name/SKILL.md"; then
        rm -rf "${target:?}/$name"
      fi
    done
  done
  rm -rf "$home"
  say "removed; the boardkit cache under ~/.cache/boardkit can go too"
  exit 0
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
if [ -n "${BOARDKIT_SOURCE:-}" ]; then
  source="$BOARDKIT_SOURCE"
else
  version="${1:-}"
  if [ -z "$version" ]; then
    version="$(git ls-remote --tags --refs "$REPO" 'v*' | sed 's|.*refs/tags/v||' \
      | grep -E '^[0-9]+\.[0-9]+\.[0-9]+$' | sort -t. -k1,1n -k2,2n -k3,3n | tail -1)"
    [ -n "$version" ] || { say "no release found at $REPO"; exit 1; }
  fi
  say "fetching boardkit $version"
  git clone --quiet --depth 1 --branch "v${version#v}" "$REPO" "$work/boardkit" 2>/dev/null \
    || { say "cannot clone $REPO at v${version#v}; is it a release, and can git reach it?"; exit 1; }
  source="$work/boardkit"
fi

# The plugin directory is the unit: its launcher reads the version from the
# manifest beside it, and its skills are generated for that version.
mkdir -p "$home" "$bin"
rm -rf "$home/plugin.new"
cp -R "$source/plugin" "$home/plugin.new"
# A release older than this script has none of its own: keep this one, so
# `board self update` can run it again.
if [ -f "$source/install.sh" ]; then cp "$source/install.sh" "$home/install.sh.new"
else cp "${BASH_SOURCE[0]}" "$home/install.sh.new"; fi
mv "$home/install.sh.new" "$home/install.sh"
rm -rf "$home/plugin" && mv "$home/plugin.new" "$home/plugin"
# A wrapper rather than a link: a launcher from before links were resolved
# looks for its manifest beside the path it was started by.
rm -f "$bin/board"
printf '#!/bin/sh\n# boardkit install.sh\nexec "%s/plugin/bin/board" "$@"\n' "$home" > "$bin/board"
chmod +x "$bin/board"
version="$(sed -n 's/.*"version": *"\([^"]*\)".*/\1/p' "$home/plugin/.claude-plugin/plugin.json")"

for target in "${targets[@]}"; do
  for skill in "$home/plugin/skills"/*/; do
    name="$(basename "$skill")"
    mkdir -p "$target/$name"
    cp "$skill/SKILL.md" "$target/$name/SKILL.md"
  done
  say "skills written to $target"
done

say "board $version installed at $bin/board"
case ":$PATH:" in
  *":$bin:"*) ;;
  *) say "$bin is not on PATH; add it, or every agent will miss \`board\`" ;;
esac
